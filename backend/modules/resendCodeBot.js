// @resendcode_bot — бот кодов подтверждения.
//
// Через него пользователю приходят коды для входа в аккаунт и действий с ним,
// когда доступ запрашивает сторонний бот (modules/botAuth.js). Сам бот ничего
// не подтверждает: код нужно передать тому боту, который его запросил.

const HELP =
  "Я @resendcode_bot — бот кодов подтверждения ИДЕЛЬ.\n\n" +
  "Сюда приходят коды для входа в аккаунт и действий с ним, когда доступ запрашивает бот. " +
  "В сообщении с кодом указано, какой бот просит доступ и что он сможет делать.\n\n" +
  "Код нужно передать именно тому боту, который его запросил. Никому другому код не сообщайте: " +
  "с ним можно войти в аккаунт.\n\n" +
  "Если вы не заказывали вход — завершите сессии в «Настройки → Сессии».";

const ACCOUNT_CODES =
  "Коды для входа в аккаунт и действий с ним приходят сюда. " +
  "Передайте код боту, который запросил доступ, и никому больше.";

/**
 * Ответ на сообщение в @resendcode_bot.
 * @returns {{message: string}}
 */
function handleResendCodeRequest(_userId, incomingText) {
  const text = String(incomingText || "").trim();
  const lower = text.toLowerCase();

  if (["/start", "/help", "начать", "старт", "помощь"].includes(lower)) {
    return { message: HELP };
  }
  // Пользователь прислал код боту — это ошибка, код нужен запросившему боту.
  if (/^\d{6}$/.test(text)) {
    return {
      message:
        "Этот код нужно передать боту, который запросил доступ, — не мне. " +
        "Если вы не заказывали вход, просто проигнорируйте сообщение и завершите сессии в настройках.",
    };
  }
  return { message: ACCOUNT_CODES };
}

module.exports = { handleResendCodeRequest, HELP };